export function magpieEnvironment({cache,key}, source=process.env) {
 const original=new Map(Object.entries(source).map(([name,value])=>[name.toUpperCase(),value]));
 const env={};
 for(const name of ['SystemRoot','WINDIR','COMSPEC','PATH','PATHEXT','SystemDrive',...locationVariables]) {
  const value=original.get(name.toUpperCase());
  if(typeof value==='string'&&value) env[name]=value;
 }
 // Magpie 自己的数据由原生便携模式定位；用户目录仅用于识别/接入用户实际安装的 Agent。
 return {...env,TEMP:cache,TMP:cache,MAGPIE_WEB_KEY:key};
}
